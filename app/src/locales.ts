export function translate(text: string, lang: "en" | "hi" | "mr") {
  if (lang === "en") return text;
  const exact = words[text];
  if (exact) return exact[lang === "hi" ? 0 : 1];
  const suffix = text.match(/^(Play Solo|Resume Solo)(.*)$/);
  if (suffix)
    return (words[suffix[1]]?.[lang === "hi" ? 0 : 1] || suffix[1]) + suffix[2];
  return text;
}
